#!/usr/bin/env node
// Builds the git.wtf wordmark (concept A, the hazard bar) as outlined vector paths, plus the icons.
// GIT.WTF!?! in Big Shoulders Display 900, off-white with the !?! in yellow, a short hazard-stripe bar above the G.
// Run after changing the spacing below: node scripts/make-logo.mjs
//
// Geometry, in units of the mark's height (100 = full height): bar 0 to 10.7, gap, caps 19 to 100 (cap height 81).
// The bar is four whole stripes on a 3 px grid at the 28 px header size, so it never ends on a sliver.

import opentype from 'opentype.js';
import { Resvg } from '@resvg/resvg-js';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const buf = readFileSync(path.join(root, 'node_modules/@fontsource/big-shoulders-display/files/big-shoulders-display-latin-900-normal.woff'));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const SIZE = 100; // font size in mark units: the caps are 0.81 of it, i.e. 81 units tall
const BASE = 100; // baseline at the foot of the mark
const TRACK = -0.4; // letter-spacing, -0.004 em
// tuned pairs, in mark units (negative tightens): the period tucks under the T's arm, the trio sits close to the F
const PAIRS = { 'T.': -4.5, '.W': -1.5, 'F!': -1.0, '!?': 0.5, '?!': 0.5 };

const text = 'GIT.WTF!?!';
const split = 7; // GIT.WTF | !?!
let x = 0;
const word = [], trio = [];
const glyphs = font.stringToGlyphs(text);
glyphs.forEach((g, i) => {
    const p = g.getPath(x, BASE, SIZE);
    (i < split ? word : trio).push(p.toPathData(2));
    let adv = (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK;
    if (i < glyphs.length - 1) {
        adv += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * SIZE;
        adv += PAIRS[text[i] + text[i + 1]] ?? 0;
    }
    x += adv;
});
// the ink box of the tuned line, so the viewBox hugs the letters
let minX = Infinity, maxX = -Infinity, maxY = -Infinity;
{
    let cx = 0;
    glyphs.forEach((g, i) => {
        const bb = g.getPath(cx, BASE, SIZE).getBoundingBox();
        if (bb.x2 > bb.x1) { minX = Math.min(minX, bb.x1); maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2); }
        let adv = (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK;
        if (i < glyphs.length - 1) { adv += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * SIZE; adv += PAIRS[text[i] + text[i + 1]] ?? 0; }
        cx += adv;
    });
}

// the hazard bar: four whole parallelograms leaning right, 3 px stripes with 3 px gaps at the 28 px header size
const U = 100 / 28; // one header pixel in mark units
const barH = 3 * U, stripe = 3 * U, pitch = 6 * U;
const barX = minX + 0.6; // sits over the G's left edge
const bars = [0, 1, 2, 3].map((k) => {
    const x0 = barX + k * pitch;
    return `M${(x0).toFixed(2)} ${barH.toFixed(2)}L${(x0 + stripe).toFixed(2)} ${barH.toFixed(2)}L${(x0 + stripe + barH).toFixed(2)} 0L${(x0 + barH).toFixed(2)} 0Z`;
}).join('');

const vbX = Math.floor(minX * 100) / 100;
const vbW = Math.ceil((maxX - vbX) * 100) / 100;
const vbH = Math.ceil(Math.max(100, maxY) * 100) / 100;
const viewBox = `${vbX} 0 ${vbW} ${vbH}`;
const data = { viewBox, width: vbW, height: vbH, word: word.join(''), trio: trio.join(''), bar: bars };

const PAPER = '#F2F0EA', YELLOW = '#FFD400', BLACK = '#0A0A0A';
const svg = (w, t, b) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><title>git.wtf</title><path fill="${b}" d="${data.bar}"/><path fill="${w}" d="${data.word}"/><path fill="${t}" d="${data.trio}"/></svg>\n`;
writeFileSync(path.join(root, 'public/logo.svg'), svg(PAPER, YELLOW, YELLOW));
writeFileSync(path.join(root, 'public/logo-black.svg'), svg(BLACK, BLACK, BLACK));
writeFileSync(path.join(root, 'src/lib/logo-data.ts'), `// Generated by scripts/make-logo.mjs from Big Shoulders Display 900. Do not edit by hand.\nexport const LOGO = ${JSON.stringify(data, null, 4)} as const;\n`);

// the icon: the !?! alone, yellow on black, the trio filling the square as in the spec (0.98 of its size)
const t0 = glyphs.slice(split);
let tx = 0; const tp = [];
let tminX = Infinity, tmaxX = -Infinity, tminY = Infinity, tmaxY = -Infinity;
t0.forEach((g, i) => {
    const p = g.getPath(tx, BASE, SIZE);
    tp.push(p.toPathData(2));
    const bb = p.getBoundingBox();
    tminX = Math.min(tminX, bb.x1); tmaxX = Math.max(tmaxX, bb.x2); tminY = Math.min(tminY, bb.y1); tmaxY = Math.max(tmaxY, bb.y2);
    tx += (g.advanceWidth / font.unitsPerEm) * SIZE - 1 + (i < t0.length - 1 ? PAIRS[text[split + i] + text[split + i + 1]] ?? 0 : 0);
});
const tw = tmaxX - tminX, th = tmaxY - tminY;
const side = Math.max(tw, th) / 0.86; // margin so the trio reads at 16 px
const ox = tminX - (side - tw) / 2, oy = tminY - (side - th) / 2;
const icon = (bg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ox.toFixed(2)} ${oy.toFixed(2)} ${side.toFixed(2)} ${side.toFixed(2)}">${bg ? `<rect x="${ox.toFixed(2)}" y="${oy.toFixed(2)}" width="${side.toFixed(2)}" height="${side.toFixed(2)}" rx="${(side * 0.14).toFixed(2)}" fill="${BLACK}"/>` : ''}<path fill="${YELLOW}" d="${tp.join('')}"/></svg>\n`;
writeFileSync(path.join(root, 'public/favicon.svg'), icon(true));
for (const [file, px] of [['favicon-16.png', 16], ['favicon-32.png', 32], ['icon-64.png', 64], ['apple-touch-icon.png', 180], ['icon-512.png', 512]]) {
    const png = new Resvg(icon(true), { fitTo: { mode: 'width', value: px } }).render().asPng();
    writeFileSync(path.join(root, 'public', file), png);
}
console.log(`wordmark ${vbW.toFixed(1)} x ${vbH} units (${(vbW / vbH).toFixed(3)}:1), icons written`);
